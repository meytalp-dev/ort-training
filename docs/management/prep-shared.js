// ===== API helpers — תקשורת עם Apps Script =====
async function prepApi(action, data) {
  const url = PREP_CONFIG.APPS_SCRIPT_URL;
  if (!url || url === 'PASTE_YOUR_APPS_SCRIPT_URL_HERE') {
    console.warn('Apps Script URL not configured');
    return { error: 'not_configured' };
  }
  try {
    const res = await fetch(url, {
      method: 'POST',
      body: JSON.stringify({ action, ...data }),
    });
    return await res.json();
  } catch (e) {
    console.error('prepApi error:', e);
    return { error: 'network' };
  }
}

async function prepListTasks(role) {
  return await prepApi('list', { role });
}

async function prepAddTask(role, task) {
  return await prepApi('add', { role, task });
}

async function prepUpdateTask(id, fields) {
  return await prepApi('update', { id, fields });
}

async function prepDeleteTask(id) {
  return await prepApi('delete', { id });
}

async function prepGetAll() {
  return await prepApi('all', {});
}

async function prepSeedDefaults(role) {
  const def = PREP_ROLES[role];
  if (!def) return;
  const tasks = def.defaultTasks.map((t, i) => ({ ...t, order: i, done: false }));
  return await prepApi('seed', { role, tasks });
}

// ===== Cache עם localStorage לטעינה מהירה =====
const prepCache = {
  get(role) {
    try {
      const raw = localStorage.getItem(`prep-tasks-${role}`);
      return raw ? JSON.parse(raw) : null;
    } catch (e) { return null; }
  },
  set(role, tasks) {
    try {
      localStorage.setItem(`prep-tasks-${role}`, JSON.stringify(tasks));
    } catch (e) {}
  },
};

// ===== עוזרים =====
function prepFormatDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  return `${d.getDate()}.${d.getMonth()+1}.${d.getFullYear()}`;
}

function prepDeadlineUrgency(iso) {
  if (!iso) return 'none';
  const today = new Date();
  today.setHours(0,0,0,0);
  const d = new Date(iso);
  const days = Math.floor((d - today) / (1000*60*60*24));
  if (days < 0) return 'overdue';
  if (days <= 7) return 'urgent';
  if (days <= 14) return 'soon';
  return 'later';
}
